create or replace function public.hipico_get_workspace()
returns setof public.hipico_workspaces
language sql
stable
security invoker
set search_path = public, pg_temp
as $$
  select workspace.*
  from public.hipico_workspaces workspace
  where workspace.owner_id = (select auth.uid())
  order by workspace.updated_at desc
  limit 1;
$$;

create or replace function public.hipico_save_workspace(
  p_name text,
  p_state jsonb,
  p_expected_version bigint default 0
)
returns public.hipico_workspaces
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_row public.hipico_workspaces;
  v_expected bigint := greatest(coalesce(p_expected_version, 0), 0);
begin
  if v_uid is null then
    raise exception 'HIPICO_AUTH_REQUIRED' using errcode = '42501';
  end if;
  if p_state is null or jsonb_typeof(p_state) <> 'object' then
    raise exception 'HIPICO_INVALID_STATE' using errcode = '22023';
  end if;

  select * into v_row
  from public.hipico_workspaces
  where owner_id = v_uid
  for update;

  if not found then
    insert into public.hipico_workspaces(owner_id, name, state, version, created_at, updated_at)
    values (v_uid, coalesce(nullif(trim(p_name), ''), 'Control Hípico'), p_state, 1, now(), now())
    returning * into v_row;
    return v_row;
  end if;

  if v_expected > 0 and v_row.version <> v_expected then
    raise exception 'HIPICO_VERSION_CONFLICT expected %, current %', v_expected, v_row.version
      using errcode = '40001';
  end if;

  update public.hipico_workspaces
  set name = coalesce(nullif(trim(p_name), ''), name),
      state = p_state,
      version = version + 1,
      updated_at = now()
  where id = v_row.id
  returning * into v_row;
  return v_row;
end;
$$;

create or replace function public.hipico_get_profile()
returns public.hipico_profiles
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_profile public.hipico_profiles;
begin
  if v_uid is null then
    raise exception 'HIPICO_AUTH_REQUIRED' using errcode = '42501';
  end if;
  select * into v_profile from public.hipico_profiles where owner_id = v_uid;
  if not found then
    insert into public.hipico_profiles(owner_id, display_name, role)
    values (v_uid, coalesce(auth.jwt() -> 'user_metadata' ->> 'name', 'Operador Hípico'), 'operator')
    returning * into v_profile;
  end if;
  return v_profile;
end;
$$;

create or replace function public.hipico_append_audit(
  p_workspace_id uuid,
  p_action text,
  p_entity_type text,
  p_entity_id text,
  p_payload jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_id bigint;
begin
  if v_uid is null then
    raise exception 'HIPICO_AUTH_REQUIRED' using errcode = '42501';
  end if;
  if p_workspace_id is not null and not exists (
    select 1 from public.hipico_workspaces
    where id = p_workspace_id and owner_id = v_uid
  ) then
    raise exception 'HIPICO_WORKSPACE_FORBIDDEN' using errcode = '42501';
  end if;
  insert into public.hipico_audit_events(owner_id, workspace_id, action, entity_type, entity_id, payload)
  values (
    v_uid,
    p_workspace_id,
    coalesce(nullif(trim(p_action), ''), 'unknown'),
    coalesce(nullif(trim(p_entity_type), ''), 'unknown'),
    nullif(trim(p_entity_id), ''),
    coalesce(p_payload, '{}'::jsonb)
  ) returning id into v_id;
  return v_id;
end;
$$;

