create extension if not exists pgcrypto;

create table if not exists public.hipico_workspaces (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null unique,
  name text not null default 'Control Hípico',
  state jsonb not null default '{}'::jsonb check (jsonb_typeof(state) = 'object'),
  version bigint not null default 1 check (version > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.hipico_profiles (
  owner_id uuid primary key,
  display_name text not null default 'Administrador Hípico',
  role text not null default 'operator' check (role in ('operator', 'admin')),
  preferences jsonb not null default '{}'::jsonb check (jsonb_typeof(preferences) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.hipico_audit_events (
  id bigint generated by default as identity primary key,
  owner_id uuid not null,
  workspace_id uuid references public.hipico_workspaces(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  payload jsonb not null default '{}'::jsonb check (jsonb_typeof(payload) = 'object'),
  created_at timestamptz not null default now()
);

create index if not exists hipico_audit_owner_time_idx
  on public.hipico_audit_events(owner_id, created_at desc);

